/** Embeds db/migrations/*.sql into db/migrations.generated.ts so serverless bundles need no filesystem access. */
import fs from "node:fs";
import path from "node:path";

const dir = path.join(process.cwd(), "db", "migrations");
const journal = JSON.parse(fs.readFileSync(path.join(dir, "meta", "_journal.json"), "utf8")) as { entries: { tag: string }[] };
const migrations = journal.entries.map((e) => ({
  id: e.tag,
  statements: fs.readFileSync(path.join(dir, `${e.tag}.sql`), "utf8").split("--> statement-breakpoint").map((s) => s.trim()).filter(Boolean),
}));
fs.writeFileSync(
  path.join(process.cwd(), "db", "migrations.generated.ts"),
  `// Generated by scripts/gen-migrations.ts from db/migrations. Do not edit.\nexport const MIGRATIONS: { id: string; statements: string[] }[] = ${JSON.stringify(migrations, null, 2)};\n`,
);
console.log(`Embedded ${migrations.length} migration(s).`);
